import { routeIntentSnapshot } from "./decision-trace-schema.mjs";
import { validateRouteCandidate } from "./route-candidate-pool.mjs";
import { cleanString, uniqueStrings as unique } from "./route-v2-utils.mjs";

export const ROUTE_CANDIDATE_SELECTION_TARGET = 3;

function generationMethod(candidate = {}) {
  const method = (candidate.supportingSignals || [])
    .find((signal) => signal?.type === "candidate-builder-method")?.value;
  return cleanString(method) || cleanString(candidate.generationSource) || "deterministic-candidate-builder";
}

function candidateSnapshot(candidate = {}, index = 0) {
  const destinations = Array.isArray(candidate.destinations) ? structuredClone(candidate.destinations) : [];
  const method = generationMethod(candidate);
  return {
    candidateId: cleanString(candidate.candidateId),
    intentId: cleanString(candidate.intentId),
    countries: unique(candidate.countries || []).map((country) => country.toUpperCase()),
    destinations,
    proposedOrder: Array.isArray(candidate.proposedOrder) ? [...candidate.proposedOrder] : [],
    durationDays: Number(candidate.durationDays) || null,
    travelStyle: cleanString(candidate.travelStyle),
    generationSource: cleanString(candidate.generationSource),
    initialReason: cleanString(candidate.initialReason) || `Generated by ${method} at stable candidate-pool position ${index + 1}.`,
    supportingSignals: Array.isArray(candidate.supportingSignals) ? structuredClone(candidate.supportingSignals) : [],
    unknowns: Array.isArray(candidate.unknowns) ? structuredClone(candidate.unknowns) : [],
    status: "pending",
    rejectionReasons: [],
    createdAt: cleanString(candidate.createdAt),
    version: cleanString(candidate.version),
    ...(candidate.inputIntentSnapshot && typeof candidate.inputIntentSnapshot === "object"
      ? { inputIntentSnapshot: structuredClone(candidate.inputIntentSnapshot) }
      : {}),
  };
}

export function selectRouteCandidates({
  candidates = [],
  context = {},
  intentId = context.intentId || "",
} = {}) {
  const intentSnapshot = routeIntentSnapshot({ context, intentId, source: "planner-candidate-sidecar" });
  const requiredCountries = new Set((intentSnapshot.targetCountries || []).map((country) => cleanString(country).toUpperCase()).filter(Boolean));
  const boundedCandidates = (Array.isArray(candidates) ? candidates : [])
    .filter((candidate) => {
      if (!cleanString(candidate?.candidateId) || !validateRouteCandidate(candidate).accepted) return false;
      const candidateCountries = new Set((candidate.countries || []).map((country) => cleanString(country).toUpperCase()).filter(Boolean));
      return [...requiredCountries].every((country) => candidateCountries.has(country));
    })
    .slice(0, ROUTE_CANDIDATE_SELECTION_TARGET);
  const pendingCandidates = boundedCandidates.map(candidateSnapshot);

  if (pendingCandidates.length < ROUTE_CANDIDATE_SELECTION_TARGET) {
    const failureReason = {
      code: "candidate-selection-minimum-not-met",
      reason: `Exactly ${ROUTE_CANDIDATE_SELECTION_TARGET} valid persisted candidates are required for selection.`,
    };
    const candidatePool = pendingCandidates.map((candidate) => ({
      ...structuredClone(candidate),
      status: "failed",
      rejectionReasons: [structuredClone(failureReason)],
    }));
    return {
      ready: false,
      reason: "candidate-selection-minimum-not-met",
      inputIntentSnapshot: intentSnapshot,
      candidatePool,
      selectedCandidate: null,
      rejectedCandidates: [],
      rejectionReasons: [],
      decisionFactors: [],
      unknowns: [
        {
          field: "candidateSelection",
          reason: `Exactly ${ROUTE_CANDIDATE_SELECTION_TARGET} stable candidates are required for the minimal selection record.`,
        },
      ],
    };
  }

  const selectedCandidate = {
    ...structuredClone(pendingCandidates[0]),
    status: "selected",
  };
  const rejectedCandidates = pendingCandidates.slice(1).map((candidate, index) => {
    const rejectionReason = {
      code: "not-selected-by-minimal-stable-order",
      reason: `Candidate remained after ${selectedCandidate.candidateId} in the deterministic candidate-pool order.`,
      selectedCandidateId: selectedCandidate.candidateId,
      candidatePoolPosition: index + 2,
    };
    return {
      ...structuredClone(candidate),
      status: "rejected",
      rejectionReasons: [rejectionReason],
    };
  });
  const statusesById = new Map([
    [selectedCandidate.candidateId, selectedCandidate],
    ...rejectedCandidates.map((candidate) => [candidate.candidateId, candidate]),
  ]);
  const candidatePool = pendingCandidates.map((candidate) => structuredClone(statusesById.get(candidate.candidateId)));

  return {
    ready: true,
    inputIntentSnapshot: intentSnapshot,
    candidatePool,
    selectedCandidate,
    rejectedCandidates,
    rejectionReasons: rejectedCandidates.map((candidate) => ({
      candidateId: candidate.candidateId,
      ...candidate.rejectionReasons[0],
    })),
    decisionFactors: [
      {
        factor: "candidate-pool-size",
        input: candidatePool.length,
        effect: "Bounds the minimal comparison to exactly three deterministic candidates.",
      },
      {
        factor: "stable-generation-order",
        input: candidatePool.map((candidate) => candidate.candidateId),
        effect: `Selects ${selectedCandidate.candidateId} as the first deterministic candidate without external evidence scoring.`,
      },
      {
        factor: "candidate-structure",
        input: selectedCandidate.proposedOrder,
        effect: "Preserves the selected candidate country, destination, and ordering snapshot for later evaluation.",
      },
    ],
    unknowns: [
      {
        field: "externalEvidence",
        reason: "The minimal selection does not call Tavily, Wikivoyage, or any other online evidence provider.",
      },
      {
        field: "comparativeQuality",
        reason: "The minimal selection records deterministic generation order only; evidence-backed quality ranking is not implemented.",
      },
    ],
  };
}
